import { StyleSheet, Text, View, TextInput, Button, Alert, FlatList,TouchableOpacity } from "react-native"; 
import React, { useState, useEffect } from "react"; 
import { database } from "./firebaseConfig"; 
import { ref, set, push, serverTimestamp, onValue } from "firebase/database"; 
import AntDesign from "@expo/vector-icons/AntDesign";
const App = () => { 
  // State to hold the task input 
  const [task, setTask] = useState(""); 
  const [tasksList, setTasksList] = useState([]); 
  const[editTaskId,setEditTaskId]=useState(null);
 
  // Define database reference to a "tasks" node 
  const tasksRef = ref(database, "tasks"); 
 
  // Handle submitting a new task 
  const handleSubmit = () => { 
    // Validate input before saving & check if task is empty 
    if (task.trim() === "") { 
      Alert.alert("Validation Error", "Please enter a task."); 
      return; 
    } 
 
    const newTaskRef = push(tasksRef); // Generates a unique key 
 
    set(newTaskRef, { 
      taskText: task, // The task text 
      createdAt: serverTimestamp(), // Firebase server timestamp 
    }) 
      .then(() => { 
        Alert.alert("Success", "Task saved!"); 
        setTask(""); // Clear input field 
      }) 
      .catch((error) => { 
        Alert.alert("Error", "Failed to save task: " + error.message); 
      }); 
  }; 
 //Handle deleting a task
 const handleDelete=(taskId)=>{
  Alert.alert(
    "Delete Task",
    "Are you sure you want to delete this task?",
    [
      { text: "Cancel", style: "cancel" },
      {
        text:"OK",
        onPress:()=>{
          const taskRef=ref(database,`tasks/${taskId}`);
          set(taskRef,null)
          .then(()=>{
            Alert.alert("Success","Task deleted");
          })
          .catch((error)=>{
            Alert.alert("Error","Failed to delete task: "+error.message);
          });

      },
      },
    ],
    { cancelable: false}
  );
 };
 //function to handle editing a task
 const handleEdit=(taskId)=>{
  const taskToEdit=tasksList.find((task)=>task.id===taskId);
  if(taskToEdit){
    setTask(taskToEdit.taskText); //Set input to current task text
    setEditTaskId(taskId); // Store the ID being edited
  }
 };
 const handleUpdate=()=>{
  //Validate that task input is not empty
  if(task.trim()===""){
    Alert.alert("Validation Error","Task text cannot be empty.");
    return;
  }
  //Ensure an edit operation is in progress
  if(!editTaskId){
    Alert.alert("Error",
    "No task selected for update.This shouldnt happen."
  );
    return;
  }
  //Create reference to the specific task being in firebase that needs updating
  const tasktoUpdateRef=ref(database,`tasks/${editTaskId}`);
  //Prepare the updated task data
  const updatedTaskData={
    taskText:task,//The new/modified task text
    //Option 1:Update timestamp to reflect edit time
    createdAt:serverTimestamp(), // Optionally update timestamp to reflect edit time
    //Option 2:Keep original timestamp by not including createdAt in the update
    //originalCreatedAt:taskList.find((task)=>task.id===editTaskId)?.createdAt || serverTimestamp(), // Preserve original timestamp if needed
  };
  //Use set() to update the task in Firebase
  set(tasktoUpdateRef,updatedTaskData)
  .then(()=>{
    Alert.alert("Success","Task updated.");
    setTask(""); // Clear input field
    setEditTaskId(null); // Exit mode by resetting editTaskId
  })
  .catch((error)=>{
    Alert.alert("Error","Failed to update task: "+error.message);
  });
 }
  // Load tasks from Firebase and listen for changes 
  useEffect(() => { 
    // onValue listens for data changes at tasksRef 
    const unsubscribe = onValue(tasksRef, (snapshot) => { 
      const data = snapshot.val(); // Get the data from the snapshot 
      if (data) { 
        // Convert data object to an array 
        const loadedTasks = Object.keys(data).map((key) => ({ 
          id: key, // The unique key generated by push() 
          ...data[key], // Spread the rest of the task data (taskText, createdAt)
        })); 
          setTasksList(loadedTasks.reverse()); // Reverse to show newest tasks first
 
        } else { 
          setTasksList([]); // If no data, set to empty array 
        } 
      }, 
      (error) => { 
        console.error("Firebase read error:", error); 
        Alert.alert("Error", "Failed to load tasks: " + error.message); 
      } 
    ); 
 
    // Cleanup: Unsubscribe from the listener when the component unmounts 
    return () => unsubscribe(); 
  }, []); // Empty dependency array: effect runs once on mount, cleans up on unmount 

 
  return ( 
    <View style={styles.container}> 
      <Text style={styles.title}>Add New Task</Text> 
 
      <TextInput 
        style={styles.input} 
        placeholder="Enter your task" 
        value={task} 
        onChangeText={(text) => setTask(text)} // Update state on text change 
      /> 
      {editTaskId ? (
        <Button title="Update Task" onPress={handleUpdate} />
      ) : (
        <Button title="Add Task" onPress={handleSubmit} />
      )}
 
      <Text style={styles.listHeader}>Tasks:</Text> 
      <FlatList 
        data={tasksList}  
        keyExtractor={(item) => item.id} 
        renderItem={({ item }) => ( 
          <View style={styles.taskItem}> 
            <Text style={styles.taskText}>{item.taskText}</Text> 

            <View style={styles.taskContainer}>
            <Text style={styles.taskDate}> 
              {item.createdAt 
                ? new Date(item.createdAt).toLocaleString() 
                : "Date not available"} 
            </Text>
            <View style={styles.taskActions}>
            <TouchableOpacity onPress={()=>handleEdit(item.id)} style={{marginRight:10}}>
              <AntDesign name="edit" size={24} color="blue" />
            </TouchableOpacity>
            <TouchableOpacity onPress={()=>handleDelete(item.id)}>
              <AntDesign name="delete" size={24} color="red" />
            </TouchableOpacity>
            </View>
            </View> 
            </View>
        )} 
        style={styles.list}
        ListEmptyComponent=
        {<Text style={styles.emptyListText}>No tasks added yet.</Text>}
      />
    </View> 
  ); 
};
export default App; 
 
